/* Generated CSS choices for one shared business DOM. No runtime dependency on design classes. */
const fs=require('node:fs'),path=require('node:path');const web=require('./project.cjs').web;
const target=path.join(web,'static/css/themes');fs.mkdirSync(target,{recursive:true});
for(const n of [1,2,3]){
 const source=fs.readFileSync(path.join(web,'static/css/rms-home-design'+n+'.css'),'utf8');
 const css='/* Generated by tools/build_themes.cjs. Select this design by copying this entire file to ../rms-selected-design.css. */\n'+source.replace(/body\.rms-site\.rms-home-design[123]/g,'body.rms-site.rms-site').replace(/body\.rms-site\.rms-design[123]/g,'body.rms-site.rms-site');
 fs.writeFileSync(path.join(target,'rms-design'+n+'.css'),css);
 if(n===1)fs.writeFileSync(path.join(web,'static/css/rms-selected-design.css'),css);
}
console.log('CSS choices built: same HTML/JS, one selected CSS file (default design 1).');